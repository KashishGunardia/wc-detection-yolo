import shutil, torch
from ultralytics import YOLO

DATA = str(DATA_YAML)
MIRROR = ('weights/last.pt', 'weights/best.pt', 'results.csv', 'args.yaml')


def _copy(src, dst):
    if not Path(src).exists():
        return False
    Path(dst).parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(src, dst)
    return True


def mirror_to_drive(trainer):
    save_dir = Path(trainer.save_dir)
    saved = []
    for rel in MIRROR:
        try:
            if _copy(save_dir / rel, DRIVE_RUN / rel):
                saved.append(rel)
        except Exception as e:
            print(f'  [mirror] failed on {rel}: {e}')
    if saved:
        print('  [mirror] -> Drive:', ', '.join(saved))


def attach_mirror(model):
    # Which of these fires first has moved between Ultralytics versions; registering
    # both means the Drive copy is never an epoch stale. Copies overwrite, so a
    # double fire is harmless.
    model.add_callback('on_model_save', mirror_to_drive)
    model.add_callback('on_fit_epoch_end', mirror_to_drive)


# ---- resume auto-detect ---------------------------------------------------
drive_last, resume_from = DRIVE_RUN / 'weights' / 'last.pt', None

if drive_last.exists():
    try:
        done_epoch = int(torch.load(drive_last, map_location='cpu', weights_only=False).get('epoch', -1))
    except Exception as e:
        done_epoch = -1
        print('could not read the Drive checkpoint:', e)

    if done_epoch >= 0:
        for rel in MIRROR:
            _copy(DRIVE_RUN / rel, LOCAL_RUN / rel)
        resume_from = LOCAL_RUN / 'weights' / 'last.pt'
        print(f'>>> RESUMING run "{RUN_NAME}" at epoch {done_epoch + 1}')
    else:
        print(f'>>> run "{RUN_NAME}" already finished - starting over and OVERWRITING it.')
        print('    (change RUN_NAME above to keep the old run)')
else:
    print(f'>>> fresh training run from {BASE_MODEL} on dataset_wc')

DEVICE = 0 if torch.cuda.is_available() else 'cpu'

if resume_from is not None:
    # resume=True re-reads epochs and hyperparameters from the checkpoint, so the model
    # must be loaded FROM the checkpoint - passing resume=True next to YOLO(BASE_MODEL)
    # silently starts over.
    model = YOLO(str(resume_from))
    attach_mirror(model)
    results = model.train(resume=True, data=DATA, device=DEVICE)
else:
    model = YOLO(BASE_MODEL)
    attach_mirror(model)
    results = model.train(
        data=DATA,
        epochs=EPOCHS,
        time=TRAIN_HOURS,      # hard wall-clock stop; overrides epochs
        imgsz=IMGSZ,
        batch=BATCH,
        patience=PATIENCE,
        seed=SEED,
        device=DEVICE,
        workers=4,
        project=str(LOCAL_PROJECT),
        name=RUN_NAME,
        exist_ok=True,
        plots=True,

        lr0=LR0,
        lrf=LRF,
        warmup_epochs=3.0,
        cos_lr=True,

        # monochrome line art: no colour to jitter, and the scale is already matched
        hsv_h=0.0, hsv_s=0.0, hsv_v=0.1,
        degrees=0.0,
        scale=0.3,
        fliplr=0.5,
        flipud=0.5,            # floorplans are drawn in any orientation, so a vertical flip is
                               # legitimate here - unusual for photos, fine for plan-view symbols
        mosaic=0.5,
        close_mosaic=10,
        mixup=0.0,
    )

mirror_to_drive(model.trainer)
print('\ntraining finished. save_dir =', model.trainer.save_dir)

n = 0
